inline uint32_t decode_utf8_next(const char*& p, const char* end) {
    if (p >= end) return 0;
    uint8_t b0 = static_cast<uint8_t>(*p++);
    if (b0 < 0x80) return b0;
    if ((b0 & 0xE0) == 0xC0 && p < end) {
        uint8_t b1 = static_cast<uint8_t>(*p++);
        return ((b0 & 0x1Fu) << 6) | (b1 & 0x3Fu);
    }
    if ((b0 & 0xF0) == 0xE0 && (p + 1) < end) {
        uint8_t b1 = static_cast<uint8_t>(*p++);
        uint8_t b2 = static_cast<uint8_t>(*p++);
        return ((b0 & 0x0Fu) << 12) | ((b1 & 0x3Fu) << 6) | (b2 & 0x3Fu);
    }
    if ((b0 & 0xF8) == 0xF0 && (p + 2) < end) {
        uint8_t b1 = static_cast<uint8_t>(*p++);
        uint8_t b2 = static_cast<uint8_t>(*p++);
        uint8_t b3 = static_cast<uint8_t>(*p++);
        return ((b0 & 0x07u) << 18) | ((b1 & 0x3Fu) << 12) | ((b2 & 0x3Fu) << 6) | (b3 & 0x3Fu);
    }
    return '?';
}

inline int font_glyph_index(uint32_t cp) {
    if (cp >= 0x20u && cp <= 0x7Eu) return static_cast<int>(cp - 0x20u);
    switch (cp) {
        case 0x00E7u: return 95;
        case 0x011Fu: return 96;
        case 0x0131u: return 97;
        case 0x0130u: return 98;
        case 0x00F6u: return 99;
        case 0x015Fu: return 100;
        case 0x00FCu: return 101;
        case 0x00C7u: return 102;
        case 0x011Eu: return 103;
        case 0x00D6u: return 104;
        case 0x015Eu: return 105;
        case 0x00DCu: return 106;
        case 0x00D7u: return 107;
        case 0x00B7u: return 108;
        case 0x00B0u: return 109;
        case 0x00B2u: return 110;
        case 0x00B3u: return 111;
        case 0x0394u: return 112;
        case 0x00B1u: return 113;
        default: return static_cast<int>('?' - 0x20);
    }
}

inline const uint8_t* font_glyph_rows(int glyph_idx) {
    if (glyph_idx < 0 || glyph_idx >= FONT_GLYPH_COUNT) glyph_idx = 0;
    return FONT_GLYPHS[glyph_idx];
}

inline std::vector<uint8_t> build_font_atlas_r8(int& out_w, int& out_h) {
    out_w = FONT_ATLAS_COLS * FONT_GLYPH_W;
    out_h = FONT_ATLAS_ROWS * FONT_GLYPH_H;
    std::vector<uint8_t> atlas(static_cast<size_t>(out_w * out_h), 0);
    for (int g = 0; g < FONT_GLYPH_COUNT; ++g) {
        int gx = (g % FONT_ATLAS_COLS) * FONT_GLYPH_W;
        int gy = (g / FONT_ATLAS_COLS) * FONT_GLYPH_H;
        for (int row = 0; row < FONT_GLYPH_H; ++row) {
            uint8_t bits = FONT_GLYPHS[g][row];
            for (int col = 0; col < FONT_GLYPH_W; ++col) {
                if (bits & (0x80u >> col)) {
                    atlas[static_cast<size_t>((gy + row) * out_w + (gx + col))] = 255;
                }
            }
        }
    }
    return atlas;
}

